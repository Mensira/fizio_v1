'use client';

import { useState } from 'react';
import {
  Activity, CheckCircle2, PauseCircle,
  User, Download,
  Plus, X, Search,
} from 'lucide-react';
import Card from '@/components/ui/Card';
import Badge from '@/components/ui/Badge';
import Button from '@/components/ui/Button';
import ProgressBar from '@/components/ui/ProgressBar';
import Input from '@/components/ui/Input';
import Select from '@/components/ui/Select';
import { useStore } from '@/lib/store';
import { t } from '@/lib/i18n';
import type { TreatmentPlan } from '@/lib/types';
import { motion, AnimatePresence } from 'framer-motion';


export default function TedaviPlanlariPage() {
  const language = useStore((s) => s.language);
  const userRole = useStore((s) => s.userRole);
  const loggedInPatientId = useStore((s) => s.loggedInPatientId);
  const treatmentPlans = useStore((s) => s.treatmentPlans);
  const updateTreatmentPlan = useStore((s) => s.updateTreatmentPlan);
  const addTreatmentPlan = useStore((s) => s.addTreatmentPlan);
  const patients = useStore((s) => s.patients);
  const showToast = useStore((s) => s.showToast);
  const tr = language === 'tr';

  const [search, setSearch] = useState('');
  const [showNewPlan, setShowNewPlan] = useState(false);
  const [statusConfirm, setStatusConfirm] = useState<{ planId: string; status: TreatmentPlan['status'] } | null>(null);

  // New plan form
  const [newPlan, setNewPlan] = useState({
    patientId: '', diagnosis: '', description: '', startDate: '', endDate: '',
    totalSessions: 10, goals: [''], modalities: [''],
  });

  const isPatient = userRole === 'patient';

  const basePlans = isPatient
    ? treatmentPlans.filter((p) => p.patientId === loggedInPatientId)
    : treatmentPlans;

  const filtered = basePlans.filter((p) => {
    if (!search.trim()) return true;
    const q = search.toLowerCase();
    return p.diagnosis.toLowerCase().includes(q) || p.patientName.toLowerCase().includes(q);
  });

  const handleStatusChange = (planId: string, newStatus: TreatmentPlan['status']) => {
    updateTreatmentPlan(planId, { status: newStatus });
    const statusLabels: Record<string, string> = { Aktif: 'Aktif', Tamamlandi: 'Tamamlandı', Askida: 'Askıda' };
    showToast(language === 'tr' ? `Plan durumu "${statusLabels[newStatus]}" olarak güncellendi.` : `Plan status updated to "${newStatus}".`);
    setStatusConfirm(null);
  };

  const handleCreatePlan = () => {
    if (!newPlan.patientId || !newPlan.diagnosis || !newPlan.startDate || !newPlan.endDate) {
      showToast(t('treatmentPlans.fillRequired', language), 'error');
      return;
    }
    const patient = patients.find((p) => p.id === newPlan.patientId);
    const plan: TreatmentPlan = {
      id: `tp-${Date.now()}`,
      patientId: newPlan.patientId,
      patientName: patient ? `${patient.firstName} ${patient.lastName}` : '',
      diagnosis: newPlan.diagnosis,
      description: newPlan.description,
      startDate: newPlan.startDate,
      endDate: newPlan.endDate,
      totalSessions: newPlan.totalSessions,
      completedSessions: 0,
      status: 'Aktif',
      goals: newPlan.goals.filter((g) => g.trim()),
      modalities: newPlan.modalities.filter((m) => m.trim()),
    };
    addTreatmentPlan(plan);
    showToast(t('treatmentPlans.created', language));
    setShowNewPlan(false);
    setNewPlan({ patientId: '', diagnosis: '', description: '', startDate: '', endDate: '', totalSessions: 10, goals: [''], modalities: [''] });
  };

  const handleExportPDF = (plan: TreatmentPlan) => {
    const prog = Math.round((plan.completedSessions / plan.totalSessions) * 100);
    const w = window.open('', '_blank');
    if (!w) return;
    w.document.write(`<html><head><title>${plan.diagnosis}</title>
      <style>body{font-family:Inter,system-ui,sans-serif;padding:40px;color:#2D3436}h1{font-size:20px;color:#2F80ED;margin-bottom:4px}.label{color:#636E72;font-size:12px}.progress{background:#E2E8F0;height:8px;border-radius:4px;margin:8px 0}.progress-bar{background:#2F80ED;height:8px;border-radius:4px}.footer{margin-top:32px;font-size:11px;color:#636E72;border-top:1px solid #E2E8F0;padding-top:12px}</style></head><body>
      <h1>FizyoPanel - ${plan.diagnosis}</h1>
      <p class="label">${language === 'tr' ? 'Hasta' : 'Patient'}: ${plan.patientName}</p>
      <p>${language === 'tr' ? 'İlerleme' : 'Progress'}: ${plan.completedSessions}/${plan.totalSessions} (${prog}%)</p>
      <div class="progress"><div class="progress-bar" style="width:${prog}%"></div></div>
      <div class="footer">${language === 'tr' ? 'Bu belge FizyoPanel sistemi tarafından oluşturulmuştur.' : 'Generated by FizyoPanel.'}</div></body></html>`);
    w.document.close();
    w.print();
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div>
          <h2 className="text-lg font-semibold text-text-main">
            {isPatient ? t('treatmentPlans.myPlans', language) : t('treatmentPlans.title', language)}
          </h2>
          <p className="text-sm text-text-secondary">
            {isPatient
              ? t('treatmentPlans.myPlansDesc', language)
              : `${basePlans.length} ${t('treatmentPlans.count', language)}`}
          </p>
        </div>
        {!isPatient && (
          <Button icon={Plus} size="sm" onClick={() => setShowNewPlan(true)}>
            {t('treatmentPlans.newPlan', language)}
          </Button>
        )}
      </div>

      {/* Search */}
      <div className="relative">
        <Search className="absolute left-3 top-1/2 -translate-y-1/2 h-4 w-4 text-text-secondary" />
        <input
          type="text"
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          placeholder={t('treatmentPlans.searchPlaceholder', language)}
          className="w-full rounded-xl border border-border bg-card pl-9 pr-4 py-2 text-sm text-text-main placeholder:text-text-secondary focus:outline-none focus:ring-2 focus:ring-primary/20"
        />
      </div>

      {/* Plans list */}
      {filtered.length === 0 ? (
        <Card>
          <p className="text-sm text-text-secondary text-center py-8">
            {t('treatmentPlans.noFound', language)}
          </p>
        </Card>
      ) : (
        <div className="space-y-3">
          {filtered.map((plan) => {
            const progress = Math.round((plan.completedSessions / plan.totalSessions) * 100);

            return (
              <motion.div key={plan.id} layout>
                <Card className="transition-shadow hover:shadow-md">
                  <div className="flex items-center justify-between gap-4">
                    <div className="flex-1 min-w-0">
                      <div className="flex items-center gap-2 flex-wrap">
                        <h3 className="text-sm font-semibold text-text-main">{plan.diagnosis}</h3>
                        <Badge variant={plan.status === 'Aktif' ? 'success' : plan.status === 'Tamamlandi' ? 'info' : 'warning'}>
                          {plan.status === 'Aktif' ? t('status.active', language) : plan.status === 'Tamamlandi' ? t('status.completed', language) : t('status.onHold', language)}
                        </Badge>
                      </div>

                      {!isPatient && (
                        <p className="flex items-center gap-1 mt-1 text-xs text-text-secondary">
                          <User className="h-3.5 w-3.5" />
                          {plan.patientName}
                        </p>
                      )}

                      <div className="mt-2 space-y-1">
                        <div className="flex items-center justify-between text-xs text-text-secondary">
                          <span>{plan.completedSessions}/{plan.totalSessions} {t('dashboard.session', language)}</span>
                          <span>%{progress}</span>
                        </div>
                        <ProgressBar
                          value={plan.completedSessions}
                          max={plan.totalSessions}
                          color={progress === 100 ? 'bg-health-green' : 'bg-primary'}
                        />
                      </div>
                    </div>

                    {/* Actions */}
                    <div className="flex flex-col items-end gap-2 flex-shrink-0">
                      <button
                        onClick={() => handleExportPDF(plan)}
                        className="flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-xs font-medium bg-primary/10 text-primary hover:bg-primary/20 transition-colors"
                      >
                        <Download className="h-3.5 w-3.5" />
                        {t('common.pdf', language)}
                      </button>

                      {!isPatient && plan.status !== 'Tamamlandi' && (
                        <div className="flex gap-1.5">
                          {plan.status === 'Aktif' && (
                            <>
                              <button
                                onClick={() => setStatusConfirm({ planId: plan.id, status: 'Tamamlandi' })}
                                className="flex items-center gap-1 rounded-lg px-2 py-1.5 text-xs font-medium bg-health-green/10 text-health-green hover:bg-health-green/20 transition-colors"
                              >
                                <CheckCircle2 className="h-3.5 w-3.5" />
                                {t('treatmentPlans.complete', language)}
                              </button>
                              <button
                                onClick={() => setStatusConfirm({ planId: plan.id, status: 'Askida' })}
                                className="flex items-center gap-1 rounded-lg px-2 py-1.5 text-xs font-medium bg-warning/10 text-warning hover:bg-warning/20 transition-colors"
                              >
                                <PauseCircle className="h-3.5 w-3.5" />
                                {t('treatmentPlans.hold', language)}
                              </button>
                            </>
                          )}
                          {plan.status === 'Askida' && (
                            <button
                              onClick={() => setStatusConfirm({ planId: plan.id, status: 'Aktif' })}
                              className="flex items-center gap-1 rounded-lg px-2 py-1.5 text-xs font-medium bg-primary/10 text-primary hover:bg-primary/20 transition-colors"
                            >
                              <Activity className="h-3.5 w-3.5" />
                              {t('treatmentPlans.activate', language)}
                            </button>
                          )}
                        </div>
                      )}
                    </div>
                  </div>
                </Card>
              </motion.div>
            );
          })}
        </div>
      )}

      {/* New Plan Modal (Doctor) */}
      <AnimatePresence>
        {showNewPlan && (
          <motion.div
            className="fixed inset-0 z-50 flex items-center justify-center p-4"
            initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }}
            onClick={() => setShowNewPlan(false)}
          >
            <div className="absolute inset-0 bg-black/40 backdrop-blur-sm" />
            <motion.div
              className="relative w-full max-w-lg max-h-[85vh] overflow-y-auto rounded-2xl bg-card shadow-2xl"
              initial={{ opacity: 0, scale: 0.95, y: 20 }}
              animate={{ opacity: 1, scale: 1, y: 0 }}
              exit={{ opacity: 0, scale: 0.95, y: 20 }}
              onClick={(e) => e.stopPropagation()}
            >
              <div className="sticky top-0 z-10 bg-card border-b border-border px-6 py-4 flex items-center justify-between">
                <h2 className="text-lg font-semibold text-text-main">{t('treatmentPlans.newPlanTitle', language)}</h2>
                <button onClick={() => setShowNewPlan(false)} className="rounded-lg p-1.5 text-text-secondary hover:bg-background">
                  <X className="h-5 w-5" />
                </button>
              </div>
              <div className="p-6 space-y-4">
                <Select
                  label={t('treatmentPlans.patient', language)}
                  value={newPlan.patientId}
                  onChange={(e) => setNewPlan({ ...newPlan, patientId: e.target.value })}
                  options={[
                    { value: '', label: t('treatmentPlans.selectPatient', language) },
                    ...patients.map((p) => ({ value: p.id, label: `${p.firstName} ${p.lastName}` })),
                  ]}
                />
                <Input label={t('treatmentPlans.diagnosis', language)} value={newPlan.diagnosis} onChange={(e) => setNewPlan({ ...newPlan, diagnosis: e.target.value })} />
                <Input label={t('treatmentPlans.description', language)} value={newPlan.description} onChange={(e) => setNewPlan({ ...newPlan, description: e.target.value })} />
                <div className="grid grid-cols-2 gap-4">
                  <Input label={t('treatmentPlans.startDate', language)} type="date" value={newPlan.startDate} onChange={(e) => setNewPlan({ ...newPlan, startDate: e.target.value })} />
                  <Input label={t('treatmentPlans.endDate', language)} type="date" value={newPlan.endDate} onChange={(e) => setNewPlan({ ...newPlan, endDate: e.target.value })} />
                </div>
                <Input label={t('treatmentPlans.totalSessions', language)} type="number" value={String(newPlan.totalSessions)} onChange={(e) => setNewPlan({ ...newPlan, totalSessions: Number(e.target.value) || 1 })} />

                {/* Goals */}
                <div>
                  <label className="block text-sm font-medium text-text-main mb-1.5">{t('treatmentPlans.goals', language)}</label>
                  {newPlan.goals.map((g, i) => (
                    <div key={i} className="flex gap-2 mb-2">
                      <input
                        className="flex-1 rounded-xl border border-border bg-background px-3 py-2 text-sm text-text-main placeholder:text-text-secondary focus:outline-none focus:ring-2 focus:ring-primary/20"
                        value={g}
                        onChange={(e) => {
                          const goals = [...newPlan.goals];
                          goals[i] = e.target.value;
                          setNewPlan({ ...newPlan, goals });
                        }}
                        placeholder={`${t('treatmentPlans.goal', language)} ${i + 1}`}
                      />
                      {newPlan.goals.length > 1 && (
                        <button onClick={() => setNewPlan({ ...newPlan, goals: newPlan.goals.filter((_, j) => j !== i) })} className="text-text-secondary hover:text-danger">
                          <X className="h-4 w-4" />
                        </button>
                      )}
                    </div>
                  ))}
                  <button onClick={() => setNewPlan({ ...newPlan, goals: [...newPlan.goals, ''] })} className="text-xs text-primary hover:text-primary/80">
                    {t('treatmentPlans.addGoal', language)}
                  </button>
                </div>

                {/* Modalities */}
                <div>
                  <label className="block text-sm font-medium text-text-main mb-1.5">{t('treatmentPlans.modalities', language)}</label>
                  {newPlan.modalities.map((m, i) => (
                    <div key={i} className="flex gap-2 mb-2">
                      <input
                        className="flex-1 rounded-xl border border-border bg-background px-3 py-2 text-sm text-text-main placeholder:text-text-secondary focus:outline-none focus:ring-2 focus:ring-primary/20"
                        value={m}
                        onChange={(e) => {
                          const modalities = [...newPlan.modalities];
                          modalities[i] = e.target.value;
                          setNewPlan({ ...newPlan, modalities });
                        }}
                        placeholder={`${t('treatmentPlans.modality', language)} ${i + 1}`}
                      />
                      {newPlan.modalities.length > 1 && (
                        <button onClick={() => setNewPlan({ ...newPlan, modalities: newPlan.modalities.filter((_, j) => j !== i) })} className="text-text-secondary hover:text-danger">
                          <X className="h-4 w-4" />
                        </button>
                      )}
                    </div>
                  ))}
                  <button onClick={() => setNewPlan({ ...newPlan, modalities: [...newPlan.modalities, ''] })} className="text-xs text-primary hover:text-primary/80">
                    {t('treatmentPlans.addModality', language)}
                  </button>
                </div>

                <Button icon={Plus} onClick={handleCreatePlan} className="w-full">
                  {t('treatmentPlans.create', language)}
                </Button>
              </div>
            </motion.div>
          </motion.div>
        )}
      </AnimatePresence>

      {/* Status Change Confirmation */}
      <AnimatePresence>
        {statusConfirm && (
          <motion.div
            className="fixed inset-0 z-50 flex items-center justify-center p-4"
            initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }}
            onClick={() => setStatusConfirm(null)}
          >
            <div className="absolute inset-0 bg-black/40 backdrop-blur-sm" />
            <motion.div
              className="relative w-full max-w-sm rounded-2xl bg-card shadow-2xl p-6"
              initial={{ opacity: 0, scale: 0.95 }}
              animate={{ opacity: 1, scale: 1 }}
              exit={{ opacity: 0, scale: 0.95 }}
              onClick={(e) => e.stopPropagation()}
            >
              <div className="text-center space-y-4">
                <div className={`mx-auto flex h-14 w-14 items-center justify-center rounded-full ${
                  statusConfirm.status === 'Tamamlandi' ? 'bg-health-green/10' : statusConfirm.status === 'Askida' ? 'bg-warning/10' : 'bg-primary/10'
                }`}>
                  {statusConfirm.status === 'Tamamlandi' ? (
                    <CheckCircle2 className="h-7 w-7 text-health-green" />
                  ) : statusConfirm.status === 'Askida' ? (
                    <PauseCircle className="h-7 w-7 text-warning" />
                  ) : (
                    <Activity className="h-7 w-7 text-primary" />
                  )}
                </div>
                <div>
                  <h3 className="text-lg font-semibold text-text-main">{t('treatmentPlans.confirmTitle', language)}</h3>
                  <p className="text-sm text-text-secondary mt-1">
                    {statusConfirm.status === 'Tamamlandi'
                      ? t('treatmentPlans.confirmComplete', language)
                      : statusConfirm.status === 'Askida'
                        ? t('treatmentPlans.confirmHold', language)
                        : t('treatmentPlans.confirmActivate', language)}
                  </p>
                </div>
                <div className="flex gap-3">
                  <button
                    onClick={() => setStatusConfirm(null)}
                    className="flex-1 rounded-xl px-4 py-2.5 text-sm font-medium bg-background border border-border text-text-main hover:bg-background/80 transition-colors"
                  >
                    {t('treatmentPlans.cancel', language)}
                  </button>
                  <button
                    onClick={() => handleStatusChange(statusConfirm.planId, statusConfirm.status)}
                    className={`flex-1 rounded-xl px-4 py-2.5 text-sm font-medium text-white transition-colors ${
                      statusConfirm.status === 'Tamamlandi' ? 'bg-health-green hover:bg-health-green/90'
                        : statusConfirm.status === 'Askida' ? 'bg-warning hover:bg-warning/90'
                          : 'bg-primary hover:bg-primary/90'
                    }`}
                  >
                    {t('treatmentPlans.yesConfirm', language)}
                  </button>
                </div>
              </div>
            </motion.div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}
